"""Generate i18n/<lang>/layers/layer-N.md for a topic.

Usage: uv run tools/build_layer_index.py <topic-id-or-path> [--check]

--check: do not write; exit 1 if any index is missing or out of date.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from topiclib import LAYERS, Topic, load_topic, load_yaml, resolve_topic, split_frontmatter  # noqa: E402

HEADER = "<!-- Generated by tools/build_layer_index.py. Do not edit by hand. -->\n\n"


def _title(path: Path, fallback: str) -> str:
    if not path.exists():
        return fallback
    meta, _ = split_frontmatter(path.read_text(encoding="utf-8"))
    return meta.get("title") or fallback


def render(topic: Topic, lang: str) -> dict[int, str]:
    lang_dir = topic.lang_dir(lang)
    lang_meta = load_yaml(lang_dir / "topic.yaml", {}) or {}
    layer_names = lang_meta.get("layers") or {}
    topic_title = lang_meta.get("title") or topic.id
    outputs = {}
    for layer in LAYERS:
        layer_name = layer_names.get(layer) or layer_names.get(str(layer)) or f"Layer {layer}"
        lines = [HEADER, f"# {topic_title} · {layer_name}\n"]
        for domain in topic.domains:
            items = []
            for concept in topic.concepts:
                if concept.get("domain") != domain:
                    continue
                if int(concept.get("first_layer", 1)) > layer:
                    continue
                cfile = topic.concept_file(lang, concept)
                title = _title(cfile, concept["id"])
                rel = f"../domains/{domain}/concepts/{concept['id']}.md#layer-{layer}"
                items.append(f"- [{title}]({rel})")
            if items:
                dtitle = _title(lang_dir / "domains" / domain / "index.md", domain)
                lines.append(f"\n## [{dtitle}](../domains/{domain}/index.md)\n\n")
                lines.append("\n".join(items) + "\n")
        outputs[layer] = "".join(lines)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("topic")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    topic = load_topic(resolve_topic(args.topic))
    stale = []
    for lang in topic.languages:
        for layer, content in render(topic, lang).items():
            target = topic.lang_dir(lang) / "layers" / f"layer-{layer}.md"
            current = target.read_text(encoding="utf-8") if target.exists() else None
            if current == content:
                continue
            if args.check:
                stale.append(str(target.relative_to(topic.path)))
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
                print(f"wrote {target.relative_to(topic.path)}")
    if stale:
        print("Out of date layer indexes:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
